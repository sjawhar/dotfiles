#!/usr/bin/env python3
"""installers/secretsd.sh configures dojo only for a matching local age identity.

The installer must retain its dotfiles and private source roots, add the optional
HOME/src/dojo root only when its encrypted secrets file names an age identity in
the local key file, and leave a converged configuration without another restart.
The fixtures use only throwaway age identities and run the real installer with a
temporary HOME, stubbed system commands, and no inherited environment.
"""

from __future__ import annotations

import os
import shutil
import stat
import subprocess
import tempfile
import unittest
from pathlib import Path

DOTFILES = Path(__file__).resolve().parents[2]
INSTALLER = DOTFILES / "installers" / "secretsd.sh"
TODAYS_TEXT = (
    "# Generated by installers/secretsd.sh — edit the installer, not this file.\n"
    "# Ordered source roots: agent-tier precedence follows declaration order,\n"
    "# local-over-shared within a root. The human tier has no precedence — a key\n"
    "# present in two roots is refused rather than silently resolved.\n"
    "[source.dotfiles]\n"
    'path = "{dotfiles}"\n'
    "\n"
    "[source.private]\n"
    'path = "{dotfiles}/.secrets"\n'
)
ENCRYPTED_VALUE = "HA_MCP_URL=ENC[AES256_GCM,data:AAAA,iv:AAAA,tag:AAAA,type:str]\n"


def write_executable(path: Path, body: str) -> None:
    path.write_text(f"#!/bin/bash\nset -euo pipefail\n{body}\n", encoding="utf-8")
    path.chmod(path.stat().st_mode | stat.S_IEXEC)


def real_age_keygen() -> str:
    """Resolve the real age-keygen before the test replaces PATH."""
    configured = os.environ.get("AGE_KEYGEN")
    if configured:
        return configured if Path(configured).is_file() and os.access(configured, os.X_OK) else ""

    mise = shutil.which("mise") or str(DOTFILES / "bin" / "mise")
    try:
        found = subprocess.run(
            [mise, "which", "-C", "/", "age-keygen"],
            capture_output=True,
            text=True,
            stdin=subprocess.DEVNULL,
            check=False,
        )
    except OSError:
        return ""
    candidate = found.stdout.strip() if found.returncode == 0 else ""
    return candidate if Path(candidate).is_file() and os.access(candidate, os.X_OK) else ""


class SecretsdInstallerConfig(unittest.TestCase):
    @classmethod
    def setUpClass(cls) -> None:
        cls.age_keygen = real_age_keygen()

    def setUp(self) -> None:
        if not self.age_keygen:
            self.fail(
                "age-keygen is unavailable: set AGE_KEYGEN to an executable or install it "
                "where `mise which -C / age-keygen` can resolve it"
            )

        self.temp_dir = tempfile.TemporaryDirectory()
        self.root = Path(self.temp_dir.name)
        self.home = self.root / "home"
        self.dotfiles = self.root / "dotfiles"
        self.mise = self.root / "mise"
        self.stubs = self.root / "stubs"
        self.log = self.root / "installer.log"
        self.config = self.home / ".config" / "secretsd" / "config.toml"
        self.keys = self.home / ".config" / "sops" / "age" / "keys.txt"
        self.dojo = self.home / "src" / "dojo"

        for directory in (
            self.home,
            self.dotfiles / ".secrets" / "secrets.human.d",
            self.mise / "installs" / "secrets" / "9.9.9" / "bin",
            self.mise / "installs" / "secrets" / "9.9.9" / "systemd",
            self.stubs,
        ):
            directory.mkdir(parents=True, exist_ok=True)

        write_executable(
            self.mise / "installs" / "secrets" / "9.9.9" / "bin" / "secrets",
            'if [ "${1:-}" = grants ]; then\n    echo "no active grants"\nfi\nexit 0',
        )
        (self.mise / "installs" / "secrets" / "9.9.9" / "systemd" / "secretsd.service").write_text(
            "test secretsd service\n", encoding="utf-8"
        )
        (self.mise / "installs" / "secrets" / "9.9.9" / "systemd" / "secretsd.socket").write_text(
            "test secretsd socket\n", encoding="utf-8"
        )
        (self.mise / "installs" / "secrets" / "latest").symlink_to("9.9.9")

        write_executable(
            self.stubs / "systemctl",
            'printf "systemctl %s\\n" "$*" >> "$SECRETSD_INSTALLER_TEST_LOG"\nexit 0',
        )
        write_executable(
            self.stubs / "sudo",
            'printf "sudo %s\\n" "$*" >> "$SECRETSD_INSTALLER_TEST_LOG"\nexit 97',
        )
        write_executable(self.stubs / "dpkg", "exit 0")

        self.env = {
            "HOME": str(self.home),
            "DOTFILES_DIR": str(self.dotfiles),
            "MISE_DATA_DIR": str(self.mise),
            "LANG": "C.UTF-8",
            "SECRETSD_INSTALLER_TEST_LOG": str(self.log),
            "PATH": f"{self.stubs}:/usr/local/bin:/usr/bin:/bin",
        }

    def tearDown(self) -> None:
        self.temp_dir.cleanup()

    def install_age_keygen_in_mise(self) -> None:
        age_keygen = self.mise / "installs" / "age" / "latest" / "age" / "age-keygen"
        age_keygen.parent.mkdir(parents=True)
        age_keygen.symlink_to(self.age_keygen)

    def install_age_keygen_in_stubs(self) -> None:
        (self.stubs / "age-keygen").symlink_to(self.age_keygen)

    def create_identity(self, name: str) -> tuple[Path, str]:
        identity = self.root / f"{name}.txt"
        generated = subprocess.run(
            [self.age_keygen, "-o", str(identity)], capture_output=True, text=True, check=False
        )
        self.assertEqual(generated.returncode, 0, generated.stdout + generated.stderr)
        with identity.open(encoding="utf-8") as identity_file:
            for line in identity_file:
                if line.startswith("# public key: "):
                    return identity, line.removeprefix("# public key: ").strip()
        self.fail(f"age-keygen did not write a public key comment to {identity}")

    def age_secret_key_line(self, identity: Path) -> str:
        with identity.open(encoding="utf-8") as identity_file:
            for line in identity_file:
                if line.startswith("AGE-SECRET-KEY-"):
                    return line
        self.fail(f"age-keygen did not write an age identity to {identity}")

    def write_key_file(self, *identities: Path) -> None:
        self.keys.parent.mkdir(parents=True)
        self.keys.write_bytes(b"".join(identity.read_bytes() for identity in identities))

    def write_dojo_secrets(self, *recipients: str) -> None:
        self.dojo.mkdir(parents=True)
        metadata = "".join(
            f"sops_age__list_{index}__map_recipient={recipient}\n"
            for index, recipient in enumerate(recipients)
        )
        (self.dojo / "secrets.env").write_text(ENCRYPTED_VALUE + metadata, encoding="utf-8")

    def todays_text(self) -> bytes:
        return TODAYS_TEXT.format(dotfiles=self.dotfiles).encode("utf-8")

    def dojo_text(self) -> bytes:
        return self.todays_text() + f'\n[source.dojo]\npath = "{self.dojo}"\n'.encode("utf-8")

    def run_installer(self) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            ["bash", str(INSTALLER)], capture_output=True, text=True, env=self.env, check=False
        )

    def assert_installed(self, result: subprocess.CompletedProcess[str], expected: bytes) -> None:
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertEqual(self.config.read_bytes(), expected, result.stdout + result.stderr)
        self.assertNotIn("AGE-SECRET-KEY-", result.stdout + result.stderr)
        self.assertNotIn("sudo", self.log.read_text(encoding="utf-8"))

    def test_1_no_key_file(self) -> None:
        self.install_age_keygen_in_mise()
        _, recipient = self.create_identity("recipient")
        self.write_dojo_secrets(recipient)

        self.assert_installed(self.run_installer(), self.todays_text())

    def test_2_no_dojo_directory(self) -> None:
        self.install_age_keygen_in_mise()
        identity, _ = self.create_identity("matching")
        self.write_key_file(identity)

        self.assert_installed(self.run_installer(), self.todays_text())

    def test_3_dojo_without_secrets_env(self) -> None:
        self.install_age_keygen_in_mise()
        identity, _ = self.create_identity("matching")
        self.write_key_file(identity)
        self.dojo.mkdir(parents=True)

        self.assert_installed(self.run_installer(), self.todays_text())

    def test_4_no_recipient_matches_a_local_identity(self) -> None:
        self.install_age_keygen_in_mise()
        matching, _ = self.create_identity("matching")
        _, other_one = self.create_identity("other-one")
        _, other_two = self.create_identity("other-two")
        self.write_key_file(matching)
        self.write_dojo_secrets(other_one, other_two, "age1yubikey1notarealrecipient")

        self.assert_installed(self.run_installer(), self.todays_text())

    def test_5_a_later_identity_matches_after_a_yubikey_identity(self) -> None:
        self.install_age_keygen_in_mise()
        identity_a, _ = self.create_identity("identity-a")
        identity_b, recipient_b = self.create_identity("identity-b")
        self.keys.parent.mkdir(parents=True)
        self.keys.write_bytes(
            identity_a.read_bytes()
            + b"AGE-PLUGIN-YUBIKEY-1made-up-identity\n"
            + identity_b.read_bytes()
        )
        self.write_dojo_secrets(recipient_b)

        self.assert_installed(self.run_installer(), self.dojo_text())
        self.log.write_text("", encoding="utf-8")
        self.assert_installed(self.run_installer(), self.dojo_text())
        self.assertNotIn("try-restart", self.log.read_text(encoding="utf-8"))

    def test_6_a_commentless_identity_uses_path_age_keygen(self) -> None:
        self.install_age_keygen_in_stubs()
        identity, recipient = self.create_identity("matching")
        self.keys.parent.mkdir(parents=True)
        self.keys.write_text(self.age_secret_key_line(identity), encoding="utf-8")
        self.write_dojo_secrets(recipient)

        self.assert_installed(self.run_installer(), self.dojo_text())


if __name__ == "__main__":
    unittest.main()
